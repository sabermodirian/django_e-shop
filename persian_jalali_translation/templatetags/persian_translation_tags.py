from django import template


register = template.Library()

@register.filter
def translate_number(nmbr_val):
    """
    ارقام انگلیسی یک مقدار را برای نمایش در قالب به ارقام فارسی تبدیل می‌کند.
    این فیلتر ابتدا مقدار ورودی را به رشته تبدیل می‌کند. سپس فقط ارقام
    انگلیسی 0 تا 9 را جایگزین می‌کند و سایر نویسه‌ها، مانند جداکننده‌ها،
    علامت منفی و حروف، بدون تغییر باقی می‌مانند.
    Args:
        nmbr_val: مقدار ورودی؛ برای مثال عدد یا رشته.
    Returns:
        str: نمایش رشته‌ای مقدار با ارقام فارسی.
    """
    # تبدیل ورودی به رشته تا فیلتر برای مقدارهای عددی نیز کار کند.
    value = str(nmbr_val)

    # ساخت جدول تبدیل؛ هر رقم انگلیسی به رقم فارسی متناظر نگاشت می‌شود.
    e2p_cnvrt = str.maketrans("0123456789", "۰۱۲۳۴۵۶۷۸۹")

    return value.translate(e2p_cnvrt)
